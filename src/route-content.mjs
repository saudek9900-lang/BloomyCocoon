export function getRoutePageSchema(screenId, { faqItems = [], products = [], hasWebp = null } = {}) {
  const route = getRouteContent(screenId);
  const canonical = getRouteCanonical(screenId);

  if (route.schemaType === 'FAQPage') {
    return {
      '@type': 'FAQPage',
      '@id': `${canonical}#faq`,
      url: canonical,
      name: route.title,
      description: route.description,
      mainEntity: faqItems,
    };
  }

  if (route.schemaType === 'Service') {
    return {
      '@type': 'Service',
      '@id': `${canonical}#service`,
      name: route.title,
      description: `${route.description} ${PAYMENT_DESCRIPTION}`,
      areaServed: [
        'Kerala',
        'Kochi',
        'Thiruvananthapuram',
        'Kozhikode',
        'Thrissur',
        'Malappuram',
        'Bengaluru',
        'Chennai',
        'Mumbai',
        'India',
      ],
      provider: {
        '@id': `${SITE_ORIGIN}/#localbusiness`,
      },
      serviceType: 'Custom crochet gifts',
    };
  }

  const page = {
    '@type': route.schemaType,
    '@id': `${canonical}#webpage`,
    url: canonical,
    name: route.title,
    description: route.schemaType === 'AboutPage' ? ENTITY_DESCRIPTION : route.description,
    isPartOf: {
      '@id': `${SITE_ORIGIN}/#website`,
    },
    about: {
      '@id': route.schemaType === 'AboutPage' ? `${SITE_ORIGIN}/#organization` : `${SITE_ORIGIN}/#localbusiness`,
    },
  };

  if (route.schemaType === 'CollectionPage') {
    const isOccasion = Boolean(OCCASION_PRODUCTS[screenId]);
    const categoryId = CATEGORY_PAGES[screenId];
    const filteredProducts = isOccasion
      ? products.filter(p => OCCASION_PRODUCTS[screenId].includes(p.id))
      : (categoryId ? products.filter(p => p.category === categoryId) : products);

    if (filteredProducts && filteredProducts.length > 0) {
      page.mainEntity = {
        '@type': 'ItemList',
        name: (isOccasion || categoryId) ? route.title : 'BloomyCocoon Handmade Crochet Gift Collection',
        description: route.description,
        numberOfItems: filteredProducts.length,
        itemListElement: filteredProducts.map((product, index) => (
          isOccasion
            ? {
                '@type': 'ListItem',
                position: index + 1,
                item: getProductSchema(product, { hasWebp }),
              }
            : {
                '@type': 'ListItem',
                position: index + 1,
                url: getProductCanonical(product.id),
                name: product.name,
                image: getSchemaImageUrl(product, hasWebp),
              }
        )),
      };
    } else {
      page.mainEntity = {
        '@type': 'ItemList',
        name: 'BloomyCocoon handmade crochet gift categories',
        itemListElement: CATEGORY_LIST.map((name, index) => ({
          '@type': 'ListItem',
          position: index + 1,
          name,
        })),
      };
    }
  }

  if (route.schemaType === 'ContactPage') {
    page.mainEntity = {
      '@id': `${SITE_ORIGIN}/#localbusiness`,
    };
  }

  return page;
}

export function getRouteSchemaGraph(screenId, options = {}) {
  const graph = [getBreadcrumbList(screenId), getRoutePageSchema(screenId, options)];
  if (options.faqItems && options.faqItems.length > 0 && ROUTE_CONTENT[screenId]?.schemaType !== 'FAQPage') {
    const canonical = getRouteCanonical(screenId);
    graph.push({
      '@type': 'FAQPage',
      '@id': `${canonical}#faq`,
      url: canonical,
      name: `${ROUTE_CONTENT[screenId]?.title || 'Gifting'} FAQ`,
      mainEntity: options.faqItems,
    });
  }
  return graph;
}

export function getProductSchemaGraph(product, { faqItems = [], hasWebp = null } = {}) {
  const graph = [getProductBreadcrumbs(product), getProductSchema(product, { hasWebp })];
  if (faqItems && faqItems.length > 0) {
    const canonical = getProductCanonical(product.id);
    graph.push({
      '@type': 'FAQPage',
      '@id': `${canonical}#faq`,
      url: canonical,
      name: `${product.name} Care & Ordering FAQ`,
      mainEntity: faqItems,
    });
  }
  return graph;
}

